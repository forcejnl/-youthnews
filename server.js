app.get("/api/articles", async (req, res) => {
  try {
    const {
      category,
      search,
      featured,
      limit = 30,
      page = 1
    } = req.query;

    const conditions = [
      `a.status='published'`
    ];

    const params = [];

    if (category) {
      params.push(category);
      conditions.push(
        `c.slug=$${params.length}`
      );
    }

    if (featured === "1") {
      conditions.push(`a.featured=TRUE`);
    }

    if (search) {
      params.push(`%${search}%`);
      const p = `$${params.length}`;

      conditions.push(
        `(a.title ILIKE ${p}
          OR a.excerpt ILIKE ${p}
          OR a.content ILIKE ${p})`
      );
    }

    const lim = Math.min(
      Number(limit) || 30,
      100
    );

    const off =
      (Math.max(Number(page) || 1, 1) - 1) *
      lim;

    params.push(lim);
    const limitParam = `$${params.length}`;

    params.push(off);
    const offsetParam = `$${params.length}`;

    const r = await query(
      `
      SELECT
        a.*,
        c.name AS category_name,
        c.slug AS category_slug
      FROM articles a
      LEFT JOIN categories c
        ON c.id=a.category_id
      WHERE ${conditions.join(" AND ")}
      ORDER BY
        a.featured DESC,
        a.published_at DESC
      LIMIT ${limitParam}
      OFFSET ${offsetParam}
      `,
      params
    );

    res.json(r.rows.map(articleRow));
  } catch (e) {
    console.error(e);
    res.status(500).json({
      error: "Failed to load articles"
    });
  }
});

