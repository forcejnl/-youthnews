/* ==========================================
   SPA FALLBACK
========================================== */

app.get("/*splat", (req, res) => {
  if (req.path.startsWith("/api/")) {
    return res.status(404).end();
  }

  res.sendFile(
    path.join(
      ROOT,
      "public",
      "index.html"
    )
  );
});

