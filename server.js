const upload = multer({ storage: multer.memoryStorage(), limits: { fileSize: 8 * 1024 * 1024 }, fileFilter: (_req, file, cb) => cb(null, /^image\/(jpeg|png|webp|gif)$/.test(file.mimetype)) });
app.post("/api/upload", requireAuth, upload.single("image"), async (req, res) => {
  try {
    if (!req.file) return res.status(400).json({ error: "Please select a JPG, PNG, WEBP, or GIF image." });
    const ext = path.extname(req.file.originalname).toLowerCase() || ".jpg";
    const storagePath = `articles/${Date.now()}-${crypto.randomBytes(6).toString("hex")}${ext}`;
    const uploadUrl = `${SUPABASE_URL}/storage/v1/object/news-images/${storagePath}`;
    const response = await fetch(uploadUrl, { method: "POST", headers: { Authorization: `Bearer ${SUPABASE_SERVICE_ROLE_KEY}`, apikey: SUPABASE_SERVICE_ROLE_KEY, "Content-Type": req.file.mimetype, "x-upsert": "false" }, body: req.file.buffer });
    if (!response.ok) { console.error("Supabase upload:", await response.text()); return res.status(500).json({ error: "Failed to upload image to Supabase." }); }
    res.json({ url: `${SUPABASE_URL}/storage/v1/object/public/news-images/${storagePath}` });
  } catch (e) { console.error(e); res.status(500).json({ error: "Image upload failed." }); }
});

