app.post("/api/login", async (req, res) => {
  try {
    const username = String(req.body.username || "").trim(); const password = String(req.body.password || "");
    if (!username || !password) return res.status(400).json({ error: "Username and password are required." });
    const r = await query("SELECT id,username,password_hash FROM users WHERE username=$1 LIMIT 1", [username]);
    if (!r.rowCount || hash(password) !== r.rows[0].password_hash) return res.status(401).json({ error: "Invalid username or password." });
    req.session.regenerate(err => {
      if (err) { console.error(err); return res.status(500).json({ error: "Could not create login session." }); }
      req.session.user = { id: r.rows[0].id, username: r.rows[0].username };
      req.session.save(saveErr => { if (saveErr) { console.error(saveErr); return res.status(500).json({ error: "Could not save login session." }); } res.json({ ok: true, username: r.rows[0].username }); });
    });
  } catch (e) { console.error(e); res.status(500).json({ error: "Login failed" }); }
});
