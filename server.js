const query = (text, params = []) => pool.query(text, params);
const hash = value => crypto.createHash("sha256").update(String(value)).digest("hex");
const slugify = value => String(value || "").trim().toLowerCase()
  .replace(/[^\u0E00-\u0E7Fa-z0-9]+/g, "-").replace(/^-+|-+$/g, "")
  || crypto.randomBytes(5).toString("hex");
const bool = value => value === true || value === 1 || value === "1" || value === "true";
const int = (value, fallback = 0) => Number.isFinite(Number(value)) ? Math.trunc(Number(value)) : fallback;
const articleRow = row => ({ ...row, featured: !!row.featured });

