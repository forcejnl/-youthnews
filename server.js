function publicArticleWhere(queryParams) {
  const conditions = ["a.status='published'"];
  const params = [];
  if (queryParams.category) { params.push(queryParams.category); conditions.push(`c.slug=$${params.length}`); }
  if (queryParams.featured === "1") conditions.push("a.featured=TRUE");
  if (queryParams.search) { params.push(`%${queryParams.search}%`); const p = `$${params.length}`; conditions.push(`(a.title ILIKE ${p} OR a.excerpt ILIKE ${p} OR a.content ILIKE ${p})`); }
  return { conditions, params };
}

