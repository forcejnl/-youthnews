/* ==========================================
   IMAGE UPLOAD - SUPABASE STORAGE
========================================== */

const storage = multer.memoryStorage();

const upload = multer({
  storage,
  limits: {
    fileSize: 8 * 1024 * 1024
  },
  fileFilter: (_, file, cb) => {
    cb(
      null,
      /^image\/(jpeg|png|webp|gif|svg\+xml)$/.test(
        file.mimetype
      )
    );
  }
});

app.post(
  "/api/upload",
  requireAuth,
  upload.single("image"),
  async (req, res) => {
    try {
      if (!req.file) {
        return res.status(400).json({
          error: "Please select an image."
        });
      }

      if (
        !SUPABASE_URL ||
        !SUPABASE_SERVICE_ROLE_KEY
      ) {
        return res.status(500).json({
          error:
            "Supabase Storage environment variables are missing."
        });
      }

      const filename =
        Date.now() +
        "-" +
        crypto.randomBytes(4).toString("hex") +
        path.extname(req.file.originalname).toLowerCase();

      const uploadUrl =
        `${SUPABASE_URL}/storage/v1/object/news-images/${filename}`;

      const uploadResponse = await fetch(
        uploadUrl,
        {
          method: "POST",
          headers: {
            Authorization:
              `Bearer ${SUPABASE_SERVICE_ROLE_KEY}`,
            apikey:
              SUPABASE_SERVICE_ROLE_KEY,
            "Content-Type":
              req.file.mimetype,
            "Cache-Control":
              "3600"
          },
          body: req.file.buffer
        }
      );

      if (!uploadResponse.ok) {
        const errorText =
          await uploadResponse.text();

        console.error(
          "Supabase upload failed:",
          errorText
        );

        return res.status(500).json({
          error:
            "Failed to upload image to Supabase."
        });
      }

      const publicUrl =
        `${SUPABASE_URL}/storage/v1/object/public/news-images/${filename}`;

      res.json({
        url: publicUrl
      });

    } catch (e) {
      console.error(
        "Image upload error:",
        e
      );

      res.status(500).json({
        error: "Image upload failed."
      });
    }
  }
);

