app.get("/api/articles", async (req, res) => {
  try {
    const status = req.query.status;
    if (status === "all" || status === "draft") {
      if (!req.session?.user) return res.status(401).json({ error: "Please login first." });
    }
    const conditions = [];
    const params = [];
    if (status === "all") { }
    else if (status === "draft") { params.push("draft"); conditions.push(`a.status=$${params.length}`); }
    else { conditions.push("a.status='published'"); }
    if (req.query.category) { params.push(req.query.category); conditions.push(`c.slug=$${params.length}`); }
    if (req.query.featured === "1") conditions.push("a.featured=TRUE");
    if (req.query.search) { params.push(`%${req.query.search}%`); const p = `$${params.length}`; conditions.push(`(a.title ILIKE ${p} OR a.excerpt ILIKE ${p} OR a.content ILIKE ${p})`); }
    const limit = Math.min(Math.max(int(req.query.limit, 30), 1), 100);
    const page = Math.max(int(req.query.page, 1), 1);
    params.push(limit); const lp = `$${params.length};`; params[params.length-1] = limit;
    params.push((page - 1) * limit); const op = `$${params.length}`;
    const where = conditions.length ? `WHERE ${conditions.join(" AND ")}` : "";
    const order = status === "all" ? "a.updated_at DESC,a.published_at DESC" : "a.featured DESC,a.published_at DESC";
    const r = await query(`SELECT a.*,c.name AS category_name,c.slug AS category_slug FROM articles a LEFT JOIN categories c ON c.id=a.category_id ${where} ORDER BY ${order} LIMIT ${lp.slice(0,-1)} OFFSET ${op}`, params);
    res.json(r.rows.map(articleRow));
  } catch (e) { console.error(e); res.status(500).json({ error: "Failed to load articles" }); }
});

